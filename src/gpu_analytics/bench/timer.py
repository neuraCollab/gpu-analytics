"""Протокол замера времени.

Правила (они же описаны в методике ВКР):
  1. Прогрев (warmup): первые запуски не учитываем. При первом запуске движок
     компилирует план, GPU инициализирует контекст и пулы памяти, ОС подгружает
     файлы в кэш. Это «разовые» расходы, а не скорость самого запроса.
  2. Повторы (repeats): запускаем несколько раз и берём медиану — она устойчива
     к случайным выбросам (фоновые процессы, сборка мусора).
  3. Разброс: межквартильный размах (IQR = Q3 − Q1) показывает, насколько
     стабильны замеры. Большой IQR — сигнал перепроверить условия эксперимента.
"""

from __future__ import annotations  # Подсказки типов нового стиля во всех версиях Python 3.

import statistics  # Медиана и квантили из стандартной библиотеки.
import time  # Точный таймер perf_counter.
from collections.abc import Callable  # Тип «функция без аргументов».
from dataclasses import dataclass  # Класс-«запись» с автоматическим конструктором.
from typing import Any  # Тип «что угодно» — результат запроса может быть любым.


@dataclass(frozen=True)  # Неизменяемая запись с результатами замера.
class Timing:
    """Результат замера: все времена и сводные статистики (в секундах)."""

    times: list[float]  # Время каждого учтённого запуска.
    median: float  # Медиана — основная метрика.
    q1: float  # Первый квартиль (25% запусков быстрее).
    q3: float  # Третий квартиль (75% запусков быстрее).

    @property  # Свойство вычисляется «на лету» из других полей.
    def iqr(self) -> float:
        """Межквартильный размах: мера разброса замеров."""
        return self.q3 - self.q1  # Разница третьего и первого квартилей.


def summarize(times: list[float]) -> Timing:
    """Посчитать медиану и квартили по списку времён."""
    if len(times) == 1:  # Если замер один — квартили посчитать нельзя...
        return Timing(times, times[0], times[0], times[0])  # ...используем единственное значение везде.
    q1, _, q3 = statistics.quantiles(times, n=4, method="inclusive")  # Делим выборку на 4 части: получаем Q1, медиану (не нужна здесь), Q3.
    return Timing(times, statistics.median(times), q1, q3)  # Медиану считаем отдельной функцией — так понятнее.


def measure(fn: Callable[[], Any], warmup: int = 1, repeats: int = 5) -> tuple[Timing, Any]:
    """Замерить функцию fn по протоколу: warmup неучтённых запусков, затем repeats учтённых.

    Возвращает (Timing, результат последнего запуска). Результат нужен, чтобы
    потом сверить ответы разных движков.
    """
    if repeats < 1:  # Защита от бессмысленных параметров.
        raise ValueError("repeats должен быть не меньше 1")  # Сообщаем об ошибке сразу, а не получаем деление на ноль позже.
    result = None  # Здесь будет результат последнего запуска.
    for _ in range(warmup):  # Прогревочные запуски («_» — переменная цикла не нужна).
        result = fn()  # Выполняем, но время не записываем.
    times = []  # Список времён учтённых запусков.
    for _ in range(repeats):  # Учтённые запуски.
        start = time.perf_counter()  # Время начала.
        result = fn()  # Выполняем запрос.
        times.append(time.perf_counter() - start)  # Записываем длительность в секундах.
    return summarize(times), result  # Возвращаем статистику и последний результат.
