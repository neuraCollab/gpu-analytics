"""Общие типы для всех запросов: «таблицы Polars» и описание одного запроса.

Вынесены в отдельный файл, чтобы их могли импортировать и файлы запросов
(queries/tpch/q01.py … q22.py), и движки (bench/engines.py), не импортируя друг друга.
"""

from __future__ import annotations  # Подсказки типов нового стиля во всех версиях Python 3.

from collections.abc import Callable  # Тип «функция»: нужен, чтобы описать поле polars в Query.
from dataclasses import dataclass  # dataclass автоматически создаёт конструктор для класса-«записи».

import polars as pl  # Библиотека Polars; принято сокращать до pl.

# Тип «таблицы Polars»: словарь «имя таблицы → ленивый датафрейм (LazyFrame)».
# LazyFrame не читает данные сразу, а строит план запроса; данные читаются при .collect().
Tables = dict[str, pl.LazyFrame]


@dataclass(frozen=True)  # frozen=True — объект нельзя изменить после создания (защищает от случайных правок).
class Query:
    """Один аналитический запрос в двух эквивалентных формах: SQL и Polars."""

    name: str  # Короткое имя, например "q1" (его пишут в командной строке: --queries q1 q6).
    tables: list[str]  # Какие таблицы читает запрос: движки откроют только их, а не все восемь.
    sql: str  # Текст запроса на SQL (для DuckDB, позже — для Spark).
    polars: Callable[[Tables], pl.LazyFrame]  # Функция: принимает таблицы, возвращает план запроса Polars.
    sort_by: list[str]  # Колонки, однозначно задающие строку: по ним оба ответа сортируются перед сверкой.


def sql_sum(expr: pl.Expr) -> pl.Expr:
    """SUM с семантикой SQL: если суммировать нечего, результат — NULL, а не 0.

    Зачем: в SQL сумма пустого набора строк равна NULL, а в Polars — 0. На маленьких
    данных (SF 0.01) фильтры Q17 не находят ни одной строки, и без этой функции
    ответы DuckDB (NULL) и Polars (0) расходятся. Нужна только для запросов, которые
    возвращают одну строку без GROUP BY: в группировке пустых групп не бывает.
    """
    # count() — число НЕпустых значений. Если их больше нуля — берём обычную сумму;
    # иначе when/then без otherwise возвращает null (как SQL на всех NULL или на пустом наборе).
    return pl.when(expr.count() > 0).then(expr.sum())
